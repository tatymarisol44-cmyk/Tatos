import hashlib
import hmac
import logging
import re
import uuid
from datetime import timedelta
from typing import TYPE_CHECKING, Any

import httpx
from sqlalchemy import Column, DateTime, Integer, String, Table, and_, insert, select, update
from sqlalchemy.exc import IntegrityError

from orchestrator.auto_reply import DEFAULT_CRISIS_HELP, REPLY_EVERY, reply_text
from orchestrator.config import Settings
from orchestrator.crisis import Intent, classify
from orchestrator.db import Database, aware, metadata, utcnow
from orchestrator.governance import AuditLog
from orchestrator.publishers import MessengerSender, PublishError, WhatsAppSender
from orchestrator.social import channel_accounts, resolve_secret

if TYPE_CHECKING:
    from orchestrator.inbox import InboxService
    from orchestrator.whatsapp_assistant import WhatsAppAssistant

SERVICE_WINDOW = timedelta(hours=24)


class ReplyRefused(ValueError):
    """The reply cannot be sent (opted out, window closed, account disabled)."""


log = logging.getLogger(__name__)

inbound_events = Table(
    "inbound_events",
    metadata,
    Column("network", String(16), primary_key=True),
    Column("message_id", String(128), primary_key=True),
    Column("tenant", String(64), nullable=False),
    Column("intent", String(16), nullable=False),
    Column("received_at", DateTime(timezone=True), nullable=False),
)

channel_alerts = Table(
    "channel_alerts",
    metadata,
    Column("tenant", String(64), primary_key=True),
    Column("alert_id", String(32), primary_key=True),
    Column("network", String(16), nullable=False),
    Column("account_id", String(32), nullable=False),
    Column("kind", String(16), nullable=False),  # crisis | human
    # The sender's address, so a professional can call back. Restricted, audited on read.
    Column("address", String(32), nullable=False),
    Column("status", String(16), nullable=False),  # open | resolved
    Column("created_at", DateTime(timezone=True), nullable=False),
    Column("resolved_by", String(128), nullable=True),
    Column("resolved_at", DateTime(timezone=True), nullable=True),
    # On-call escalation (ADR 0017): the level last notified, when the next level is due
    # (null: nothing more to do), and who took the alert, which stops the escalation.
    Column("escalation_level", Integer, nullable=False, default=0, server_default="0"),
    Column("next_escalation_at", DateTime(timezone=True), nullable=True),
    Column("acknowledged_by", String(128), nullable=True),
    Column("acknowledged_at", DateTime(timezone=True), nullable=True),
    # The patient, when the alert comes from their app (a test answer); null for a message.
    Column("subject_id", String(64), nullable=True),
)

channel_optouts = Table(
    "channel_optouts",
    metadata,
    Column("tenant", String(64), primary_key=True),
    Column("network", String(16), primary_key=True),
    Column("address_key", String(64), primary_key=True),
    Column("created_at", DateTime(timezone=True), nullable=False),
)

# The last automatic reply of each kind to each (pseudonymous) number: the rate limit.
channel_auto_replies = Table(
    "channel_auto_replies",
    metadata,
    Column("tenant", String(64), primary_key=True),
    Column("network", String(16), primary_key=True),
    Column("address_key", String(64), primary_key=True),
    Column("kind", String(16), primary_key=True),
    Column("last_sent_at", DateTime(timezone=True), nullable=False),
)

SYSTEM_ACTOR = "channel:whatsapp"


def normalize_address(address: str) -> str:
    return re.sub(r"\D", "", address)


def address_key(key: bytes, tenant: str, network: str, address: str) -> str:
    """A keyed pseudonym of a phone number (HMAC-SHA256 with PSEUDONYM_KEY, which is never
    stored in the database). A plain hash would not do: there are only ~10^8 mobile
    numbers in Ecuador, so anyone holding a database copy could hash them all in minutes
    and learn who asked a mental-health practice to stop writing (re-identification test
    in tests/test_reidentification.py)."""
    message = f"{tenant}:{network}:{normalize_address(address)}".encode()
    return hmac.new(key, message, hashlib.sha256).hexdigest()


def _alert(row: Any) -> dict[str, Any]:
    return {c.name: getattr(row, c.name) for c in channel_alerts.c if c.name != "tenant"}


async def deliver(
    settings: Settings,
    transport: httpx.AsyncBaseTransport | None,
    network: str,
    account_external_id: str,
    token: str,
    to: str,
    body: str,
) -> str:
    """Send one text on a channel; the platform's message id. Raises PublishError when the
    platform refuses and httpx.TransportError when the outcome is unknown (never retried
    automatically: it may have been delivered)."""
    async with httpx.AsyncClient(
        timeout=settings.publish_timeout_seconds, transport=transport
    ) as client:
        if network == "whatsapp":
            return await WhatsAppSender(client, settings.whatsapp_graph_base).send_text(
                phone_number_id=account_external_id,
                token=token,
                to=normalize_address(to),
                body=body,
            )
        bases = {"facebook": settings.messenger_graph_base, "instagram": settings.meta_graph_base}
        if network not in bases:
            raise PublishError(f"no direct messages on {network}")
        return await MessengerSender(client, bases[network]).send_text(
            account_id=account_external_id, token=token, to=to, body=body
        )


class InboundService:
    def __init__(
        self,
        db: Database,
        audit: AuditLog,
        settings: Settings,
        transport: httpx.AsyncBaseTransport | None = None,
    ) -> None:
        self.db = db
        self.audit = audit
        self.settings = settings
        self.transport = transport  # tests replace the network
        self.pseudonym_key = settings.pseudonym_secret()
        self.assistant: WhatsAppAssistant | None = None  # set by the orchestrator
        self.inbox: InboxService | None = None  # set by the orchestrator (ADR 0023)

    async def reply(self, tenant: str, alert_id: str, actor: str, body: str) -> dict[str, Any]:
        """A person's reply to an alert. Returns the outcome, never the text."""
        query = (
            select(channel_alerts, channel_accounts.c.external_id, channel_accounts.c.secret_ref)
            .join(
                channel_accounts,
                and_(
                    channel_accounts.c.tenant == channel_alerts.c.tenant,
                    channel_accounts.c.account_id == channel_alerts.c.account_id,
                    channel_accounts.c.active.is_(True),
                ),
                isouter=True,
            )
            .where(and_(channel_alerts.c.tenant == tenant, channel_alerts.c.alert_id == alert_id))
        )
        async with self.db.engine.connect() as conn:
            row = (await conn.execute(query)).first()
        if row is None:
            raise KeyError(alert_id)
        if row.network not in ("whatsapp", "instagram", "facebook"):
            raise ReplyRefused(f"replies by {row.network} are not supported")
        if row.external_id is None:
            raise ReplyRefused("the account is disabled")
        if await self.is_opted_out(tenant, row.network, row.address):
            raise ReplyRefused("the person asked not to be contacted [WA-OPT-IN]")
        created = aware(row.created_at)
        if created is None or utcnow() - created > SERVICE_WINDOW:
            raise ReplyRefused(
                "outside the 24-hour window only an approved template may be sent [WA-WINDOW]"
            )

        outcome, message_id = await self._deliver(
            row.network, row.external_id, row.secret_ref, row.address, body
        )
        await self.audit.record(
            tenant,
            actor,
            f"channel_alert.reply_{outcome}",
            f"channel_alert/{alert_id}",
            details={"message_id": message_id},
        )
        return {"alert_id": alert_id, "outcome": outcome, "message_id": message_id}

    async def account_for(self, network: str, external_id: str) -> tuple[str, str] | None:
        """The one tenant and account an incoming platform id belongs to; None if unknown
        or ambiguous (two tenants claiming the same id get nothing, not a guess)."""
        query = select(channel_accounts.c.tenant, channel_accounts.c.account_id).where(
            and_(
                channel_accounts.c.network == network,
                channel_accounts.c.external_id == external_id,
                channel_accounts.c.active.is_(True),
            )
        )
        async with self.db.engine.connect() as conn:
            rows = (await conn.execute(query)).all()
        if len(rows) != 1:
            if rows:
                log.warning("inbound %s: %d tenants claim the same account id", network, len(rows))
            return None
        return rows[0].tenant, rows[0].account_id

    async def handle_message(
        self, network: str, external_id: str, message_id: str, sender: str, text: str
    ) -> str:
        """Classify one message and act on it; returns the outcome (never the text)."""
        owner = await self.account_for(network, external_id)
        if owner is None:
            return "unknown_account"
        tenant, account_id = owner
        intent = classify(text)
        now = utcnow()
        try:
            async with self.db.engine.begin() as conn:
                await conn.execute(
                    insert(inbound_events).values(
                        network=network,
                        message_id=message_id,
                        tenant=tenant,
                        intent=intent,
                        received_at=now,
                    )
                )
                if intent == "stop":
                    key = address_key(self.pseudonym_key, tenant, network, sender)
                    exists = await conn.execute(
                        select(channel_optouts.c.address_key).where(
                            and_(
                                channel_optouts.c.tenant == tenant,
                                channel_optouts.c.network == network,
                                channel_optouts.c.address_key == key,
                            )
                        )
                    )
                    if exists.first() is None:
                        await conn.execute(
                            insert(channel_optouts).values(
                                tenant=tenant, network=network, address_key=key, created_at=now
                            )
                        )
                    await self.audit.record_in(
                        conn, tenant, SYSTEM_ACTOR, "channel.opt_out", f"channel_optout/{key[:12]}"
                    )
                elif intent in ("crisis", "human"):
                    alert_id = uuid.uuid4().hex[:12]
                    await conn.execute(
                        insert(channel_alerts).values(
                            tenant=tenant,
                            alert_id=alert_id,
                            network=network,
                            account_id=account_id,
                            kind=intent,
                            address=normalize_address(sender)[:32],
                            status="open",
                            created_at=now,
                            escalation_level=0,
                            next_escalation_at=now,  # the on-call notifier takes it now
                        )
                    )
                    await self.audit.record_in(
                        conn,
                        tenant,
                        SYSTEM_ACTOR,
                        f"channel_alert.{intent}",
                        f"channel_alert/{alert_id}",
                    )
        except IntegrityError:
            return "duplicate"  # already handled: Meta delivered it again
        if intent == "crisis":
            # No personal data in logs: the alert id is enough for the on-duty person.
            log.warning("crisis alert opened for tenant %s", tenant)
        if self.inbox is not None:
            try:
                await self.inbox.record_inbound(
                    tenant, network, account_id, sender, text, intent, message_id
                )
            except Exception:  # the alert and the reply must not depend on the inbox
                log.exception("inbox: incoming message not recorded")
        if network == "whatsapp" and self.settings.whatsapp_auto_reply:
            await self._auto_reply(network, tenant, account_id, sender, intent, text)
        elif network in ("instagram", "facebook") and self.settings.social_auto_reply:
            # Fixed texts only (crisis containment, "a person will write", STOP): everyday
            # questions there get an AI draft in the inbox, sent by the professional.
            await self._auto_reply(network, tenant, account_id, sender, intent, text)
        return intent

    async def _claim_reply(
        self, tenant: str, key: str, intent: Intent, network: str = "whatsapp"
    ) -> bool:
        """True when this replica may send now: the last reply of this kind to this number
        is older than its interval. A conditional UPDATE, else an INSERT; a concurrent
        replica loses on the row count or on the primary key."""
        now = utcnow()
        where = and_(
            channel_auto_replies.c.tenant == tenant,
            channel_auto_replies.c.network == network,
            channel_auto_replies.c.address_key == key,
            channel_auto_replies.c.kind == intent,
        )
        async with self.db.engine.begin() as conn:
            updated = await conn.execute(
                update(channel_auto_replies)
                .where(
                    and_(where, channel_auto_replies.c.last_sent_at <= now - REPLY_EVERY[intent])
                )
                .values(last_sent_at=now)
            )
            if updated.rowcount == 1:
                return True
            exists = await conn.execute(select(channel_auto_replies.c.kind).where(where))
            if exists.first() is not None:
                return False  # replied recently
        try:
            async with self.db.engine.begin() as conn:
                await conn.execute(
                    insert(channel_auto_replies).values(
                        tenant=tenant,
                        network=network,
                        address_key=key,
                        kind=intent,
                        last_sent_at=now,
                    )
                )
        except IntegrityError:
            return False  # another replica claimed it first
        return True

    async def _auto_reply(
        self,
        network: str,
        tenant: str,
        account_id: str,
        sender: str,
        intent: Intent,
        message: str,
    ) -> None:
        if intent == "other" and await self.is_opted_out(tenant, network, sender):
            return  # they asked us to stop: only a crisis is still answered
        key = address_key(self.pseudonym_key, tenant, network, sender)
        body: str | None = None
        kind: str = intent
        if intent == "other" and network != "whatsapp":
            return  # Instagram and Facebook: an AI draft in the inbox instead
        if intent == "other" and self.assistant is not None and self.settings.whatsapp_ai_replies:
            # The model writes everyday answers (whatsapp_assistant.py).
            body, needs_human = await self.assistant.compose(tenant, key, sender, message)
            if needs_human:
                await self._open_alert(tenant, account_id, sender, "human")
            kind = "assistant"
        if body is None:
            if not await self._claim_reply(tenant, key, intent, network):
                return
            body = reply_text(
                intent,
                self.settings.practice_display_name,
                self.settings.crisis_help_text or DEFAULT_CRISIS_HELP,
            )
            kind = intent
        await self._send(network, tenant, account_id, sender, body, kind)

    async def _open_alert(self, tenant: str, account_id: str, sender: str, kind: str) -> None:
        """An alert for the team (e.g. a new person who chose a time by WhatsApp)."""
        await self.open_alert(tenant, kind, "whatsapp", account_id, sender)

    async def open_alert(
        self,
        tenant: str,
        kind: str,
        network: str,
        account_id: str,
        address: str,
        subject_id: str | None = None,
    ) -> str:
        """An alert for the team, taken by the on-call notifier at once (ADR 0017). The
        patient's app opens one too (`network` "app", self_report.py), naming the patient
        in `subject_id`."""
        alert_id = uuid.uuid4().hex[:12]
        now = utcnow()
        async with self.db.engine.begin() as conn:
            await conn.execute(
                insert(channel_alerts).values(
                    tenant=tenant,
                    alert_id=alert_id,
                    network=network,
                    account_id=account_id,
                    kind=kind,
                    address=normalize_address(address)[:32],
                    subject_id=subject_id,
                    status="open",
                    created_at=now,
                    escalation_level=0,
                    next_escalation_at=now,
                )
            )
            await self.audit.record_in(
                conn,
                tenant,
                SYSTEM_ACTOR,
                f"channel_alert.{kind}",
                f"channel_alert/{alert_id}",
                subject_id=subject_id,
            )
        return alert_id

    async def _send(
        self, network: str, tenant: str, account_id: str, sender: str, body: str, kind: str
    ) -> None:
        query = select(channel_accounts.c.external_id, channel_accounts.c.secret_ref).where(
            and_(
                channel_accounts.c.tenant == tenant,
                channel_accounts.c.account_id == account_id,
                channel_accounts.c.active.is_(True),
            )
        )
        async with self.db.engine.connect() as conn:
            account = (await conn.execute(query)).first()
        if account is None:
            return
        outcome, message_id = await self._deliver(
            network, account.external_id, account.secret_ref, sender, body
        )
        # The audit names the kind and the outcome, never the number or the text.
        await self.audit.record(
            tenant,
            SYSTEM_ACTOR,
            f"channel.auto_reply_{outcome}",
            f"channel_account/{account_id}",
            details={"intent": kind, "message_id": message_id},
        )
        if self.inbox is not None:  # the professional sees what the person received
            try:
                await self.inbox.record_outbound(
                    tenant, network, account_id, sender, body, f"auto:{kind}", outcome, message_id
                )
            except Exception:
                log.exception("inbox: automatic reply not recorded")

    async def _deliver(
        self, network: str, external_id: str, secret_ref: str, to: str, body: str
    ) -> tuple[str, str | None]:
        """(outcome, platform message id): dry_run without a token, else sent, failed or
        uncertain (a transport error: maybe delivered, never retried automatically)."""
        token = resolve_secret(secret_ref)
        if token is None:
            return "dry_run", None
        try:
            message_id = await deliver(
                self.settings, self.transport, network, external_id, token, to, body
            )
        except PublishError as exc:
            log.warning("%s message failed: %s", network, type(exc).__name__)
            return "failed", None
        except httpx.TransportError:
            return "uncertain", None
        return "sent", message_id

    async def is_opted_out(self, tenant: str, network: str, address: str) -> bool:
        query = select(channel_optouts.c.address_key).where(
            and_(
                channel_optouts.c.tenant == tenant,
                channel_optouts.c.network == network,
                channel_optouts.c.address_key
                == address_key(self.pseudonym_key, tenant, network, address),
            )
        )
        async with self.db.engine.connect() as conn:
            return (await conn.execute(query)).first() is not None

    async def alerts(
        self, tenant: str, actor: str, status: str | None = "open"
    ) -> list[dict[str, Any]]:
        query = select(channel_alerts).where(channel_alerts.c.tenant == tenant)
        if status is not None:
            query = query.where(channel_alerts.c.status == status)
        query = query.order_by(channel_alerts.c.created_at, channel_alerts.c.alert_id)
        async with self.db.engine.connect() as conn:
            rows = [_alert(r) for r in await conn.execute(query)]
        # Reading callers' numbers is itself audited.
        await self.audit.record(
            tenant, actor, "channel_alert.read", "channel_alerts", details={"count": len(rows)}
        )
        return rows

    async def resolve(self, tenant: str, alert_id: str, actor: str) -> bool:
        query = (
            update(channel_alerts)
            .where(
                and_(
                    channel_alerts.c.tenant == tenant,
                    channel_alerts.c.alert_id == alert_id,
                    channel_alerts.c.status == "open",
                )
            )
            .values(
                status="resolved",
                resolved_by=actor,
                resolved_at=utcnow(),
                next_escalation_at=None,  # resolved: nobody else needs to be called
            )
        )
        async with self.db.engine.begin() as conn:
            done = (await conn.execute(query)).rowcount == 1
            if done:
                await self.audit.record_in(
                    conn, tenant, actor, "channel_alert.resolved", f"channel_alert/{alert_id}"
                )
        return done
