"""Incoming WhatsApp, Instagram Direct and Facebook Messenger messages (ADR 0015 M4,
ADR 0023), privacy by design.

* **Classified on arrival** (`crisis.classify`). The text is kept only **sealed** in the
  inbox (inbox.py, ADR 0023), readable by the clinician role; these tables keep the
  outcome, never the text.
* **Deduplicated** by the platform's message id: Meta retries failed deliveries for up to
  36 hours and does not guarantee single delivery.
* **STOP** records an opt-out under a pseudonymous key, SHA-256 of tenant and number.
  Phone numbers are a small space, so this is pseudonymous, not anonymous (it is still
  personal data); it is enough to suppress future sends without keeping the number.
* **Crisis and requests for a person** open an alert for the practice's staff, with the
  number so a professional can call back. The AI never answers these.
* **Warm automatic replies** (owner's decision P6, `auto_reply.py`): fixed, reviewed texts by
  intent, never generated by a model; crisis replies carry the emergency lines; each kind
  is rate-limited per sender, claimed in the database so two replicas never both send.
  On Instagram and Facebook only these fixed texts go out by themselves; everyday
  questions get an AI draft in the inbox, which the professional sends.
* **A person may reply** to an alert inside the 24-hour customer service window (counted
  from the alert, which is conservative), unless the sender opted out. The audit records
  that a reply was sent, by whom and how it went, never the text."""

